    private function __construct() {}

    /** Chave do catálogo: `BDE-01`, `bde-1` e (`BDE`, `01`) viram `BDE-1`; sem tipo, só o código. */
    public static function chave(?string $codigo, ?string $tipo = null): string
    {
        $codigo = strtoupper(trim((string) $codigo));
        if ($tipo === null && str_contains($codigo, '-')) {
            [$codigo, $tipo] = explode('-', $codigo, 2);
        }
        $tipo = trim((string) $tipo);
        if ($tipo === '') {
            return $codigo;
        }

        return $codigo . '-' . (ctype_digit($tipo) ? (string) (int) $tipo : strtoupper($tipo));
    }

    public static function existe(?string $codigo, ?string $tipo): bool
    {
        return isset(self::EVENTOS[self::chave($codigo, $tipo)]);
    }

    /** Descrição oficial do evento, ou null se ele não estiver no catálogo ou não tiver descrição. */
    public static function descricao(?string $codigo, ?string $tipo): ?string
    {
        return self::EVENTOS[self::chave($codigo, $tipo)][0] ?? null;
    }

    /** Situação do evento no catálogo, ou null (fora do catálogo, sem descrição ou `EST`). */
    public static function situacao(?string $codigo, ?string $tipo): ?SituacaoRastreamento
    {
        return self::EVENTOS[self::chave($codigo, $tipo)][1] ?? null;
    }

    /** `EST`: "Favor desconsiderar a informação anterior". */
    public static function anulaAnterior(?string $codigo): bool
    {
        return in_array(strtoupper(trim((string) $codigo)), self::ANULAM_ANTERIOR, true);
    }

    /** @return array<string, ?string> chave => descrição, em ordem de código e tipo */
    public static function todos(): array
    {
        return array_map(static fn(array $evento): ?string => $evento[0], self::EVENTOS);
    }
